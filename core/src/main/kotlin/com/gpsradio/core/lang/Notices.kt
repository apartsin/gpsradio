package com.gpsradio.core.lang

/**
 * Short spoken notices for things the listener must hear, not just see (voice is the main channel,
 * spec A §32): failures, unavailable features, tour changes. Written out per language because they
 * must work without a model (offline, out of credit). Unknown languages get English.
 */
enum class Notice {
    ANSWER_FAILED,
    QUESTIONS_OFFLINE,
    QUESTIONS_NEED_KEY,
    TOUR_NO_GPS,
    TOUR_TOO_FEW_SIGHTS,
    TOUR_ABANDONED,
    OFFLINE_NOTES,
    DEGRADED_NOTES,
    BUDGET_REACHED,
    /** Spoken while the listener waits for the next story (spec A §59), varied so it never sounds like a loop. */
    WAIT_1,
    WAIT_2,
    WAIT_3,
    /** Shown the moment "next" is heard (spec A §59). */
    NEXT_STORY,
    /** The phone's model carries on (spec A §72): out of OpenAI credit, offline, OpenAI down, over the limit, no key. */
    QUOTA_MODEL,
    OFFLINE_MODEL,
    DEGRADED_MODEL,
    BUDGET_MODEL,
    PREVIEW_MODEL,
}

